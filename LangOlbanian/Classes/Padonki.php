     * Фонетические правила (regex → замена), применяются к словам, которых нет в словаре.
     */
    private const array RULES = [
        // -ться/-тся → -цца/-ца
        '/ться(?!\p{L})/u' => 'цца',
        '/тся(?!\p{L})/u'  => 'ца',
