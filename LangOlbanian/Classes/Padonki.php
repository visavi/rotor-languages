    /**
     * Основы склоняемых слов (начало слова → замена, окончание сохраняется).
     * Ловит падежи: автор/автора/автору/авторы → аффтар/аффтара/аффтару/аффтары.
     */
    private const array STEMS = [
        'автор'     => 'аффтар',
        'красавчик' => 'кросавчег',
        'девушк'    => 'дефачк',
        'человек'   => 'чилавек',
        'голов'     => 'галав',
