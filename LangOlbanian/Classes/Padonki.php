    /**
     * Коверкает HTML, пропуская теги и блоки script/style/pre/code/textarea.
     */
    public static function distort(string $html): string
    {
        $result = preg_replace_callback(
            '/<(script|style|pre|code|textarea)\b[^>]*>.*?<\/\1>|<[^>]*>|[^<]+/isu',
            static fn (array $m): string => $m[0][0] === '<' ? $m[0] : self::text($m[0]),
            $html
        );

        return $result ?? $html;
    }

    /**
     * Коверкает текстовый кусок по словам: слово из словаря берётся финально
     * (правила его не трогают), остальные слова прогоняются через фонетические правила.
     */
    private static function text(string $text): string
    {
        return preg_replace_callback('/\p{L}+/u', static function (array $m): string {
            $word = $m[0];
            $lower = mb_strtolower($word);

            if (isset(self::DICT[$lower])) {
                return self::matchCase($word, self::DICT[$lower]);
            }

            // Склоняемые основы: меняем начало слова, окончание оставляем
            foreach (self::STEMS as $stem => $replace) {
                if (str_starts_with($lower, $stem)) {
                    return self::matchCase($word, $replace . mb_substr($word, mb_strlen($stem)));
                }
            }

            return preg_replace(array_keys(self::RULES), array_values(self::RULES), $word);
        }, $text);
    }

    /**
     * Переносит регистр первой буквы исходного слова на замену.
     */
    private static function matchCase(string $source, string $replace): string
    {
        $first = mb_substr($source, 0, 1);

        if (mb_strtoupper($first) === $first && mb_strtolower($first) !== $first) {
            return mb_strtoupper(mb_substr($replace, 0, 1)) . mb_substr($replace, 1);
        }

        return $replace;
    }
}
